// The Docker image's NGINX site, made from apps/web/public/_headers so a self-hosted Ream sends the same security
// policy and caching as ream.deityhub.com (Cloudflare Pages reads _headers itself; NGINX needs them as add_header).
//   node scripts/nginx-conf.ts [path to _headers] > default.conf
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const file = process.argv[2] ?? join(import.meta.dirname, '../apps/web/public/_headers')

/** path pattern -> its headers, in file order */
const rules: { path: string; headers: [string, string][] }[] = []
for (const line of readFileSync(file, 'utf8').split('\n')) {
  if (!line.trim() || line.trimStart().startsWith('#')) continue
  if (!/^\s/.test(line)) rules.push({ path: line.trim(), headers: [] })
  else {
    const at = line.indexOf(':')
    if (at < 0 || !rules.length) throw new Error(`can't read this _headers line: ${line}`)
    rules.at(-1)!.headers.push([line.slice(0, at).trim(), line.slice(at + 1).trim()])
  }
}

const every = rules.filter((r) => r.path === '/*').flatMap((r) => r.headers)
// pages and anything without a rule of its own are checked for a newer version each time, like Cloudflare Pages does
const fallback: [string, string][] = [['Cache-Control', 'public, max-age=0, must-revalidate']]
const quote = (v: string) => `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
// NGINX drops inherited add_header lines in a location that has its own, so each location repeats all of them
const block = (headers: [string, string][]) => {
  const merged = new Map<string, string>()
  for (const [k, v] of [...fallback, ...every, ...headers]) merged.set(k, v)
  return [...merged].map(([k, v]) => `    add_header ${k} ${quote(v)} always;`).join('\n')
}
const location = (path: string) => (path.endsWith('/*') ? `location ${path.slice(0, -1)}` : `location = ${path}`)

const out = [
  '# generated by scripts/nginx-conf.ts from apps/web/public/_headers: edit those, not this',
  'server {',
  '  listen 8080;',
  '  root /usr/share/nginx/html;',
  '  index index.html;',
  '  server_tokens off;',
  // a real 404 status with the app's own page (Cloudflare Pages does the same with 404.html)
  '  error_page 404 /404.html;',
  '',
  '  location / {',
  '    try_files $uri $uri/ =404;',
  block([]),
  '  }',
  '',
  // NGINX's type list has no .webmanifest; browsers want the manifest's own type (Cloudflare sends it)
  '  location = /manifest.webmanifest {',
  '    default_type application/manifest+json;',
  '    try_files $uri =404;',
  block([]),
  '  }',
  ...rules
    .filter((r) => r.path !== '/*')
    .flatMap((r) => ['', `  ${location(r.path)} {`, '    try_files $uri =404;', block(r.headers), '  }']),
  '}',
  '',
]
process.stdout.write(out.join('\n'))
